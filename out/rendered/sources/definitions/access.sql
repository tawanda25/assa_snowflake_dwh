-- Roles per environment
DEFINE ROLE ASSA_ENV_ADMIN_DEV;
DEFINE ROLE ASSA_ENV_READER_DEV;

-- Role hierarchy
GRANT ROLE ASSA_ENV_READER_DEV TO ROLE ASSA_ENV_ADMIN_DEV;
GRANT ROLE ASSA_ENV_ADMIN_DEV TO ROLE ACCOUNTADMIN;

-- Admin: full access
GRANT USAGE ON DATABASE ASSA_DEV_DWH TO ROLE ASSA_ENV_ADMIN_DEV;
GRANT USAGE ON SCHEMA ASSA_DEV_DWH.EXTRACT TO ROLE ASSA_ENV_ADMIN_DEV;
GRANT USAGE ON SCHEMA ASSA_DEV_DWH.STAGE TO ROLE ASSA_ENV_ADMIN_DEV;
GRANT USAGE ON SCHEMA ASSA_DEV_DWH.WAREHOUSE TO ROLE ASSA_ENV_ADMIN_DEV;
GRANT ALL ON ALL TABLES IN SCHEMA ASSA_DEV_DWH.EXTRACT TO ROLE ASSA_ENV_ADMIN_DEV;
GRANT ALL ON ALL TABLES IN SCHEMA ASSA_DEV_DWH.STAGE TO ROLE ASSA_ENV_ADMIN_DEV;
GRANT ALL ON ALL TABLES IN SCHEMA ASSA_DEV_DWH.WAREHOUSE TO ROLE ASSA_ENV_ADMIN_DEV;

-- Reader: consumption layer only
GRANT USAGE ON DATABASE ASSA_DEV_DWH TO ROLE ASSA_ENV_READER_DEV;
GRANT USAGE ON SCHEMA ASSA_DEV_DWH.WAREHOUSE TO ROLE ASSA_ENV_READER_DEV;
GRANT SELECT ON ALL TABLES IN SCHEMA ASSA_DEV_DWH.WAREHOUSE TO ROLE ASSA_ENV_READER_DEV;